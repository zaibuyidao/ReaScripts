const SendPlusLocale = value => Object.prototype.hasOwnProperty.call(SendPlusLanguages, value) ? value : "en";
const SendPlusPluralRules = new Map();
function SendPlusTranslate(locale, key, values = {}) {
  const language = SendPlusLocale(locale);
  const messageLanguage = SendPlusI18n[language][key] == null ? "en" : language;
  let message = SendPlusI18n[language][key] ?? SendPlusI18n.en[key] ?? key;
  if (typeof message === "object") {
    if (!SendPlusPluralRules.has(messageLanguage)) SendPlusPluralRules.set(messageLanguage, new Intl.PluralRules(messageLanguage));
    message = message[SendPlusPluralRules.get(messageLanguage).select(values.n)] ?? message.other;
  }
  return message.replace(/\{(\w+)\}/g, (match, name) => values[name] ?? match);
}
